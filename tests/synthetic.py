def golden_tavily_responder(request: httpx.Request) -> httpx.Response:
    """Per-query Tavily payloads: three planted items, everything else empty."""
    body = json.loads(request.content.decode("utf-8"))
    query = body.get("query", "")
    results: list[dict[str, str]] = []
    if query == f'"{GOLDEN_NAME}" fraud':
        results = [_tavily_result(GOLDEN_MEDIA_ITEMS[0])]
    elif query == f'"{GOLDEN_NAME}" regulator':
        results = [_tavily_result(GOLDEN_MEDIA_ITEMS[1])]
    elif query == f'"{GOLDEN_NAME}" lawsuit':
        results = [_tavily_result(GOLDEN_MEDIA_ITEMS[2])]
    return httpx.Response(
        200,
        json={
            "query": query,
            "results": results,
            "response_time": 0.01,
        },
    )


def _tavily_result(item: dict[str, str]) -> dict[str, Any]:
    return {
        "title": item["title"],
        "url": item["url"],
        "content": item["content"],
        "score": 0.9,
        "published_date": item["published_date"],
    }


def empty_tavily_responder(request: httpx.Request) -> httpx.Response:
    body = json.loads(request.content.decode("utf-8"))
    return httpx.Response(
        200, json={"query": body.get("query", ""), "results": [], "response_time": 0.01}
    )


