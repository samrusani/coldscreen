@pytest.mark.parametrize(
    ("level", "triggered"),
    [
        ("green", []),
        ("red", ["R1"]),
        ("red", ["R4"]),  # cited, but no contradiction survives the downgrade
    ],
)
def test_golden_floor_holds_at_amber_when_no_contradiction_survives(
    level: str, triggered: list[str]
) -> None:
    """Without a surviving contradicted assessment the mechanical floor
    (A1, A2) still holds and no fabricated red can lift the level."""
    casefile = load_casefile(GOLDEN_DIR)
    unresolvable = [
        assessment_json("CLM-001", "contradicted", ["ZZZ-001"], "Note."),
        assessment_json("CLM-002", "unverified", [], "Note."),
        assessment_json("CLM-004", "unverified", [], "Note."),
    ]
    provider = FakeModelProvider([synthesis_json(level, triggered, assessments=unresolvable)])
    result = synthesize(casefile, provider, provider_name="fake", model="anchor-probe")
    assert result.verdict.level == "amber"
    assert {"A1", "A2"} <= set(result.verdict.triggered)
    assert "R4" not in result.verdict.triggered


def test_adversarial_trigger_ids_never_reach_the_memo() -> None:
    """Markdown, URLs, banned words, and an em dash inside fake trigger ids
    must leave no trace in the rendered memo: notes are count-only."""
    casefile = load_casefile(AMBER_DIR)
    em_dash = "\u2014"
    hostile = [
        "[R1](https://evil.example/fraud)",
        "R1 fraud injection",
        f"R9{em_dash}sneaky",
        "**bold** `markdown`",
    ]
    provider = FakeModelProvider([synthesis_json("red", [*hostile, "A1", "A2"])])
    result = synthesize(casefile, provider, provider_name="fake", model="hostile")
    memo = render_memo(apply_synthesis(casefile, result))
    for fragment in (
        "evil.example",
        "fraud",
        em_dash,
        "**bold**",
        "`markdown`",
        "sneaky",
        "[R1]",
    ):
        assert fragment not in memo
    assert find_banned_terms(memo) == []
    assert "dropped 4 unrecognized trigger id(s)" in memo
    assert result.verdict.level == "amber"


