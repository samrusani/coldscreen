def canned_response(fixture_dir: Path, name: str = "synthesis_response.json") -> str:
    raw = (fixture_dir / name).read_text(encoding="utf-8")
    return json.dumps(json.loads(raw))


def fake_synthesis(fixture_dir: Path, label: str) -> tuple[CaseFile, SynthesisResult]:
    casefile = load_casefile(fixture_dir)
    provider = FakeModelProvider([canned_response(fixture_dir)])
    result = synthesize(casefile, provider, provider_name="fake", model=label)
    return casefile, result


def ollama_reply(content: str) -> httpx.Response:
    return httpx.Response(
        200,
        json={
            "model": "fake-model:1b",
            "message": {"role": "assistant", "content": content},
            "done": True,
        },
    )


def claim_texts(casefile: CaseFile) -> tuple[str, ...]:
    return tuple(claim.text for claim in casefile.claims)


